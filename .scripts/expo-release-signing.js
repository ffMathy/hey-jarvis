// Signs Android release builds with a real upload key when one is supplied, and the debug key
// otherwise. Shared by `mobile/app.config.ts` and `watch/app.config.ts`.
//
// **Plain CommonJS JavaScript, and in `.scripts/` rather than beside either app, for one reason:**
// Expo transpiles `app.config.ts` into an `app.config.js` next to it and then `require`s that with
// plain Node, which resolves `.js` and `.json` and never `.ts`. A shared TypeScript module is
// therefore invisible to it — everything typechecks, and the app dies at build time with "Cannot
// find module". The types live in `expo-release-signing.d.ts` beside this.
//
// **And it imports nothing**, which is the second half of the same problem: Bun's isolated linker
// puts `@expo/config-plugins` in each app's own `node_modules`, and a file in `.scripts/` has no
// app above it to resolve from. So `withAppBuildGradle` is handed in by whichever config is asking
// rather than required here. Requiring it directly fails at export time with "Cannot find module
// '@expo/config-plugins'", which is how this was found.
//
// It is shared rather than copied because the two apps have to be signed by the *same key* to be
// delivered as one Play listing, and two copies of a signing config are two things that can drift.
//
// Android will not install an unsigned app, so React Native's template signs release builds with a
// debug keystore — the same well-known key on every machine, committed into the template. That is
// fine for side-loading and useless for Play: anyone holding that key can sign an "update" your
// phone will accept. What this adds is a second signing config, used only when the four Gradle
// properties below are present, so `expo run:android` and the plain APK builds are untouched.
//
// **The properties arrive as `ORG_GRADLE_PROJECT_…` environment variables, never on the command
// line.** Anything passed as `-P` is visible in `ps` to every other process on the machine, and on
// a shared CI runner that is a password in public.
//
// Written as a plugin because `android/` is generated by prebuild: an edit made there is lost the
// next time anyone runs it. It appends a second `android { }` block rather than rewriting the one
// the template produced, which is the same thing to Gradle — the block is a method call on an
// extension, and calling it twice merges — and does not depend on the template's exact wording.

const MARKER = '// --- Jarvis upload signing (.scripts/expo-release-signing.js) ---';

/**
 * The Gradle property that decides whether there is an upload key at all.
 *
 * Only this one is tested. If the store file is given and a password is not, the build should fail
 * loudly rather than quietly fall back to the debug key and produce something Play will refuse.
 */
const STORE_FILE = 'JARVIS_UPLOAD_STORE_FILE';

const createReleaseSigning = (withAppBuildGradle) => (config) =>
  withAppBuildGradle(config, (gradle) => {
    if (gradle.modResults.contents.includes(MARKER)) {
      return gradle;
    }
    gradle.modResults.contents += `
${MARKER}
if (project.hasProperty('${STORE_FILE}')) {
    android {
        signingConfigs {
            upload {
                storeFile file(project.property('${STORE_FILE}'))
                storePassword project.property('JARVIS_UPLOAD_STORE_PASSWORD')
                keyAlias project.property('JARVIS_UPLOAD_KEY_ALIAS')
                keyPassword project.property('JARVIS_UPLOAD_KEY_PASSWORD')
            }
        }
        buildTypes {
            release {
                signingConfig signingConfigs.upload
            }
        }
    }
}
`;
    return gradle;
  });

/**
 * The build number Play orders uploads by, which is not the version anybody reads.
 *
 * Play will not accept two uploads with the same `versionCode`, ever, on any track. It has nothing
 * to do with `version` in the config, which is the name a human sees and may stay the same across a
 * dozen test builds.
 *
 * **The phone and the watch must not share one either.** They go into the same Play listing under
 * the same package name, and a version code has to be unique across every form factor in it — so
 * CI gives the phone an even number and the watch the odd one above it, which can never collide and
 * never goes backwards. `offset` is which of the two this app is.
 */
function androidVersionCode(offset) {
  const given = Number(process.env.JARVIS_ANDROID_VERSION_CODE);
  const base = Number.isInteger(given) && given > 0 ? given : 1;
  return base * 2 + offset;
}

/**
 * The version a human reads, which is the monorepo's own released version.
 *
 * Not `versionCode`, and not related to it: this is the string Play shows on the listing and in the
 * Console's release list, and the one the two apps have to agree on because they are one listing.
 *
 * It is read from the root `package.json` rather than written into either app config, because that
 * is the number Release Please bumps when a release is cut on `main` — so the bundle a production
 * release publishes is stamped with the version of the release that published it, without anything
 * having to thread a value through the workflow. Both apps were previously frozen at the `0.1.0`
 * the Expo template shipped with, which made every upload in the Console look like the last one.
 *
 * `require` rather than an import, for the same reason nothing else here imports: this file is
 * loaded by plain Node out of `.scripts/`, and `../package.json` is the repository root from here.
 */
function androidVersionName() {
  return require('../package.json').version;
}

module.exports = { createReleaseSigning, androidVersionCode, androidVersionName };
